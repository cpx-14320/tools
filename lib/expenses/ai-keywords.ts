/** 記帳用語 → 分類的關鍵字對照表。
 *
 *  **這是給「沒有 API 金鑰時的模擬解析」用的，但它本身不是暫時的替代品。** 接上真模型
 *  之後它一樣有用：常見的店名跟用詞先在本地判掉，剩下真的看不懂的才送去問模型——每一次
 *  本地命中就是省下來的一次 API 費用。
 *
 *  **設計原則**
 *
 *  1. **對應的是「分類名稱」不是 id**：每個人的分類 id 都不一樣，而且會自己改名、增刪。
 *     所以這裡存的是候選名稱清單，由 resolve 時去比對那個使用者實際有的分類。
 *
 *  2. **候選由具體排到通用**：`["午餐", "餐飲", "飲食"]` ——先試「午餐」這種子分類，
 *     沒有才退到大分類。**同一個概念的不同叫法要全部列出來**：預設分類改版過，舊帳號叫
 *     「餐飲」「水電」「保養品」「家電」「電話費」「繳稅」，新帳號叫「飲食」「住家」
 *     「美妝保養」「3C電器」「電信」「稅金」。只寫一種的話，另一種的使用者會**整本字典
 *     都配不到**——這是這張表最容易悄悄失效的地方。
 *
 *  3. **長的關鍵字優先**：「全家便當」要比「全家」先比對到。比對時會自動照長度排序，
 *     不用在這裡手動排。
 *
 *  4. **重疊的詞只算一次，而且照「可信度」挑**：關鍵字分成五組，由可信到含糊是
 *     用途（房租、電話費、薪水）→ 餐別（午餐）→ 品項（便當）→ 店名（全家）→ 模糊字
 *     （書、貓）。「全家便當 100」兩組都中，要的是「便當→午餐」而不是「全家」；
 *     「Uber Eats 250」要的是外送而不是計程車。見 matchKeywordCategories。
 *
 *  5. **純英數的關鍵字用「詞邊界」比對**：`net`（NET 服飾）不能中在 `netflix` 裡面、
 *     `gu` 不能中在 `guava` 裡面。中文沒有這個問題（中文字不算 \w，邊界永遠成立），
 *     所以只對 ASCII 關鍵字加這層限制。
 *
 *  6. **只放「幾乎不會歧義」的詞**：「蘋果」可能是水果也可能是 3C，這種就不要收——
 *     配錯比配不到糟，配不到至少會進待確認區讓使用者自己選，配錯卻可能被直接確認掉。
 *
 *  **店名為什麼放這麼多**：記帳時實際打的是「全家」「五十嵐」「屈臣氏」，不是「餐飲」
 *  「飲料」「保養品」。品類詞只接得到少數認真描述的那幾筆，店名才是真正能把命中率拉
 *  起來的部分，所以每一類都盡量把台灣常見的連鎖品牌補齊。 */

