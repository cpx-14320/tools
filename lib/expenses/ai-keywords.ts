/** 記帳用語 → 分類的關鍵字對照表。
 *
 *  **這是給「沒有 API 金鑰時的模擬解析」用的，但它本身不是暫時的替代品。** 接上真模型
 *  之後它一樣有用：常見的店名跟用詞先在本地判掉，剩下真的看不懂的才送去問模型——每一次
 *  本地命中就是省下來的一次 API 費用。
 *
 *  **設計原則**
 *
 *  1. **對應的是「分類名稱」不是 id**：每個人的分類 id 都不一樣，而且會自己改名、增刪。
 *     所以這裡存的是候選名稱清單，由 resolve 時去比對那個使用者實際有的分類。
 *
 *  2. **候選由具體排到通用**：`["午餐", "餐飲"]` ——先試「午餐」這種子分類，
 *     沒有才退到「餐飲」。這樣有細分類的人會被歸得更準，沒細分的人也不會配不到。
 *
 *  3. **長的關鍵字優先**：「全家便當」要比「全家」先比對到，不然「全家」會先中。
 *     比對時會自動照長度排序，不用在這裡手動排。
 *
 *  4. **純英數的關鍵字用「詞邊界」比對**：`net`（NET 服飾）不能中在 `netflix` 裡面、
 *     `gu` 不能中在 `guava` 裡面。中文沒有這個問題（中文字不算 \w，邊界永遠成立），
 *     所以只對 ASCII 關鍵字加這層限制，見 matchKeywordCategories。
 *
 *  5. **只放「幾乎不會歧義」的詞**：「蘋果」可能是水果也可能是 3C，這種就不要收——
 *     配錯比配不到糟，配不到至少會進待確認區讓使用者自己選，配錯卻可能被直接確認掉。
 *
 *  **店名為什麼放這麼多**：記帳時實際打的是「全家」「五十嵐」「屈臣氏」，不是「餐飲」
 *  「飲料」「保養品」。品類詞只接得到少數認真描述的那幾筆，店名才是真正能把命中率拉
 *  起來的部分，所以每一類都盡量把台灣常見的連鎖品牌補齊。 */

