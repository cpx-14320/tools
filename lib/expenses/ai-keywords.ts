/** 比對時用的清單，長的關鍵字排前面——「全家便當」要比「全家」先中。 */
export const KEYWORDS_BY_LENGTH: string[] = Object.keys(KEYWORD_CATEGORIES).sort((a, b) => b.length - a.length);

/** 純英數的關鍵字先編成帶詞邊界的 regex（見檔頭原則 4）。模組載入時做一次就好，
 *  每解析一段文字都要跑完整張表，在迴圈裡 new RegExp 會重編好幾百次。 */
const ASCII_PATTERNS = new Map<string, RegExp>(
  KEYWORDS_BY_LENGTH.filter((k) => /^[\x20-\x7e]+$/.test(k)).map((k) => [
    k,
    new RegExp(`\\b${k.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}\\b`, "i"),
  ]),
);

/** 這一段文字命中哪些候選分類名稱（已經照關鍵字長度排好優先序）。
 *
 *  英文關鍵字（netflix、uber…）比對時兩邊都轉小寫，中文不受影響。 */
export function matchKeywordCategories(fragment: string): string[] {
  const lower = fragment.toLowerCase();
  for (const keyword of KEYWORDS_BY_LENGTH) {
    const pattern = ASCII_PATTERNS.get(keyword);
    if (pattern ? pattern.test(fragment) : lower.includes(keyword)) return KEYWORD_CATEGORIES[keyword];
  }
  return [];
}
